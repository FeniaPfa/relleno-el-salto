/* ---------- terreno cartográfico generado por shader ---------- */
var VERT = [
'varying vec2 vUv; varying vec3 vW;',
'void main(){',
'  vUv = uv;',
'  vW  = position;',
'  gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0);',
'}'].join('\n');

var FRAG = [
'precision highp float;',
'uniform sampler2D hmap;',
'uniform float emin, emax, lv, texel, metros, exag, contorno;',
'varying vec2 vUv; varying vec3 vW;',
'',
'float hraw(vec2 uv){',
'  vec3 c = texture2D(hmap, uv).rgb;',
'  float q = floor(c.r*255.0+0.5)*8.0 + floor(floor(c.g*255.0+0.5)/32.0);',
'  return emin + (q/lv)*(emax-emin);',
'}',
/* los dos bytes no se interpolan por separado: NEAREST + bilineal a mano */
'float hgt(vec2 uv){',
'  vec2 p = uv/texel - 0.5;',
'  vec2 i = floor(p), f = fract(p);',
'  float a = hraw((i+vec2(0.5,0.5))*texel);',
'  float b = hraw((i+vec2(1.5,0.5))*texel);',
'  float c = hraw((i+vec2(0.5,1.5))*texel);',
'  float d = hraw((i+vec2(1.5,1.5))*texel);',
'  return mix(mix(a,b,f.x), mix(c,d,f.x), f.y);',
'}',
'float hash(vec2 p){ return fract(sin(dot(p,vec2(127.1,311.7)))*43758.5453123); }',
'float vnoise(vec2 p){',
'  vec2 i=floor(p), f=fract(p); vec2 u=f*f*(3.0-2.0*f);',
'  return mix(mix(hash(i),hash(i+vec2(1.0,0.0)),u.x),',
'             mix(hash(i+vec2(0.0,1.0)),hash(i+vec2(1.0,1.0)),u.x),u.y);',
'}',
'float fbm(vec2 p){',
'  float s=0.0,a=0.5;',
'  for(int k=0;k<5;k++){ s+=a*vnoise(p); p*=2.03; a*=0.5; }',
'  return s;',
'}',
'',
'void main(){',
'  float e  = texel;',
'  float hc = hgt(vUv);',
'  float hL = hgt(vUv-vec2(e,0.0)), hR = hgt(vUv+vec2(e,0.0));',
'  float hD = hgt(vUv-vec2(0.0,e)), hU = hgt(vUv+vec2(0.0,e));',
'  float paso = 2.0*e*metros;',
'  float dx = (hR-hL)/paso;',
'  float dz = (hU-hD)/paso;',
'  float lap = (hL+hR+hU+hD)*0.25 - hc;',       /* >0 = cóncavo: quebrada */
'',
'  /* detalle submétrico procedural: nunca se pixela */',
'  vec2 wp = vW.xz;',
'  float n1 = fbm(wp/46.0);',
'  float n2 = fbm(wp/13.0);',
'  float nx = fbm(wp/46.0+vec2(0.6,0.0)) - n1;',
'  float nz = fbm(wp/46.0+vec2(0.0,0.6)) - n1;',
'',
'  vec3 nor = normalize(vec3(-(dx+nx*0.34)*exag, 1.0, (dz+nz*0.34)*exag));',
'',
'  vec3 sol  = normalize(vec3(-0.62, 0.70, -0.35));',
'  vec3 rell = normalize(vec3( 0.55, 0.42,  0.72));',
'  float key = max(dot(nor,sol ),0.0);',
'  float fil = max(dot(nor,rell),0.0);',
'  float sh  = 0.44 + 0.56*pow(key,0.80) + 0.14*fil;',
'',
'  float t    = clamp((hc-emin)/(emax-emin),0.0,1.0);',
'  float pend = clamp(length(vec2(dx,dz)),0.0,1.6);',
'  float conc = clamp(lap*0.55+0.5,0.0,1.0);',
'',
'  /* la vegetación se concentra en quebradas y cotas bajas */',
'  float veg = clamp(conc*1.5 - t*0.55 + (n1-0.5)*0.95 + (n2-0.5)*0.35, 0.0, 1.0);',
'  vec3 suelo = mix(vec3(0.58,0.46,0.35), vec3(0.85,0.80,0.67), smoothstep(0.22,0.96,t));',
'  vec3 verde = mix(vec3(0.19,0.30,0.18), vec3(0.39,0.45,0.27), n2);',
'  vec3 col   = mix(suelo, verde, veg);',
'  col = mix(col, vec3(0.62,0.57,0.49), smoothstep(0.55,1.35,pend)*0.50);',
'  col *= 0.95 + 0.10*n2;',
'  col *= sh;',
'',
'  /* curvas de nivel: finas cada 50 m, índice cada 250 m */',
'  if(contorno > 0.5){',
'    float ci = 50.0;',
'    float f  = fract(hc/ci);',
'    float w  = fwidth(hc/ci)*1.1;',
'    float ln = 1.0 - smoothstep(0.0, max(w,0.001), min(f,1.0-f));',
'    float fi = fract(hc/250.0);',
'    float wi = fwidth(hc/250.0)*1.1;',
'    float li = 1.0 - smoothstep(0.0, max(wi,0.001), min(fi,1.0-fi));',
'    col = mix(col, col*0.62, ln*0.42);',
'    col = mix(col, col*0.42, li*0.55);',
'  }',
'  gl_FragColor = vec4(col, 1.0);',
'}'].join('\n');

function matCarto(){
  return new THREE.ShaderMaterial({
    uniforms:{
      hmap:{value:texAlt}, emin:{value:M.emin}, emax:{value:M.emax},
      lv:{value:M.lv}, texel:{value:1.0/M.n}, metros:{value:S},
      exag:{value:K()}, contorno:{value:1.0}
    },
    vertexShader:VERT, fragmentShader:FRAG,
    extensions:{derivatives:true}
  });
}
